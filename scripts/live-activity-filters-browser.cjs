// Production routes, isolated MariaDB; fixture contains 25 newer London events.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.SAVED_BASE_URL;
const output = path.resolve(__dirname, '../.impeccable/review/live-filters');
fs.mkdirSync(output, { recursive: true });
const checks = [];
const check = (label, value) => { assert.ok(value, label); checks.push(label); };
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(base + '/happening-now');
    const root = page.locator('[data-live-page]');
    const form = root.locator('[data-live-filter-form]');
    await page.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 20);
    check('Global top twenty excludes older Berlin', !(await root.textContent()).includes('Berlin music beyond twenty'));
    await form.locator('summary').click();
    await form.getByLabel('Music', { exact: true }).waitFor();
    await form.getByLabel('Location', { exact: true }).selectOption('city');
    await form.getByLabel('City', { exact: true }).fill(' Berlin ');
    await form.getByLabel('Two-letter country').fill('de');
    await form.getByLabel('Music', { exact: true }).check();
    await form.getByRole('button', { name: 'Apply', exact: true }).click();
    await root.locator('[data-live-list]').getByText('Berlin music beyond twenty').waitFor();
    check('Complete-window city/type match', await root.locator('[data-live-list] li').count() === 1);
    check('Quiet Apply', await root.locator('[data-live-badge]').textContent() === '');
    check('Readable scope', (await root.locator('[data-live-summary]').textContent()).includes('Berlin, DE · Music'));
    const stored = await page.evaluate(() => localStorage.getItem('ticketopia-live-filters-v1'));
    check('Only public filter settings stored', !/event_title|actor|account|connections/.test(stored));
    const browsing = await context.newPage();
    const streamRequest = browsing.waitForRequest(request => request.url().includes('/activity/stream?'));
    await browsing.goto(base + '/community');
    const streamFilter = JSON.parse(new URL((await streamRequest).url()).searchParams.get('filter'));
    check('Toasts use the same confirmed city/type filter', streamFilter.location.city === 'Berlin' && streamFilter.category_ids.join() === 'Music');
    check('Filtered navigation establishes quiet toast baseline', await browsing.locator('[data-live-toasts] li').count() === 0);
    await browsing.close();
    const second = await context.newPage(); await second.goto(base + '/happening-now');
    await second.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    check('Guest second tab restores filters', true); await second.close(); await page.bringToFront();
    const event = root.locator('[data-live-list] a'); await event.click();
    await page.waitForURL('**/events/**');
    check('Filtered event opens Overview', !new URL(page.url()).searchParams.has('section'));
    await page.locator('[data-return-results]').click(); await page.waitForURL('**/happening-now*');
    await page.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    check('Return restores filter', true);
    await form.locator('summary').click();
    await form.getByLabel('Music', { exact: true }).waitFor();
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      check('No filter overflow ' + width, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      if (width !== 390) await root.screenshot({ path: path.join(output, width + '.png') });
    }
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
    check('Enlarged filter text wraps', await root.evaluate(el => [el, ...el.querySelectorAll('*')].every(node => !node.getBoundingClientRect().width || node.getBoundingClientRect().right <= innerWidth + 1)));
    await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' });
    await page.keyboard.press('Tab');
    await form.getByRole('button', { name: 'Apply', exact: true }).focus();
    check('Keyboard focus visible', await form.getByRole('button', { name: 'Apply', exact: true }).evaluate(el => getComputedStyle(el).outlineStyle !== 'none'));
    if (process.env.AXE_SCRIPT) { await page.addScriptTag({ path: process.env.AXE_SCRIPT }); check('Filter accessibility', (await page.evaluate(async () => (await axe.run(document.querySelector('[data-live-activity]'))).violations)).length === 0); }
    await form.getByLabel('City', { exact: true }).fill('No such city'); await form.getByRole('button', { name: 'Apply', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('[data-live-connection]').textContent.includes('match these filters'));
    check('Honest empty result', await root.locator('[data-live-list] li').count() === 0);
    await form.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 20);
    check('Reset restores all events', true);
    const owner = await browser.newContext(); await owner.addCookies([{ name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base }]);
    const signed = await owner.newPage(); await signed.goto(base + '/happening-now');
    await signed.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 20);
    const signedForm = signed.locator('[data-live-filter-form]');
    await signedForm.locator('summary').click();
    await signedForm.getByLabel('Music', { exact: true }).check();
    await signedForm.getByRole('button', { name: 'Apply', exact: true }).click();
    await signed.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    const pref = await (await owner.request.get(base + '/api/v1/me/live-activity-preferences')).json();
    check('Account preference saved', pref.filters.category_ids.join() === 'Music' && pref.revision === 2);
    const native = await browser.newContext({ javaScriptEnabled: false }); await native.addCookies([{ name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base }]);
    const nativePage = await native.newPage(); await nativePage.goto(base + '/me/preferences');
    const nativeForm = nativePage.locator('form[action="/me/live-activity-preferences"]');
    await nativeForm.locator('summary').click(); await nativeForm.getByRole('button', { name: 'Reset filters' }).click();
    await nativePage.waitForURL('**/me/preferences?saved=preferences');
    const reset = await (await owner.request.get(base + '/api/v1/me/live-activity-preferences')).json();
    check('JavaScript-disabled Reset saves', reset.filters.category_ids.length === 0 && reset.enabled);
    await signed.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 20);
    check('Native change replaces active account feed', true);
    const me = await (await owner.request.get(base + '/api/v1/me')).json();
    check('Private participation fixture', (await owner.request.put(base + '/api/v1/me/event-interests/ticketmaster:Browser_0', { data: { visibility: 'private' }, headers: { 'X-CSRF-Token': me.csrf_token } })).ok());
    await signed.goto(base + '/events/ticketmaster:Browser_0?section=community');
    await signed.locator('[data-recommendation-editor] summary').click();
    const composer = signed.locator('[data-recommendation-form] textarea');
    await composer.fill('Keep this unsubmitted filter journey draft');
    await composer.evaluate(el => { window.fixtureComposer = el; });
    const settings = await owner.newPage(); await settings.goto(base + '/happening-now');
    const settingsForm = settings.locator('[data-live-filter-form]');
    await settingsForm.locator('summary').click();
    await settingsForm.getByLabel('Music', { exact: true }).check();
    await settingsForm.getByRole('button', { name: 'Apply', exact: true }).click();
    await settings.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    await signed.evaluate(() => window.dispatchEvent(new Event('focus')));
    check('Apply preserves mounted composer and draft', await composer.evaluate(el => el === window.fixtureComposer && el.value === 'Keep this unsubmitted filter journey draft'));
    check('Apply preserves private selected participation', await signed.locator('[data-interest-form]:not([data-interest-edit]) button').getAttribute('aria-pressed') === 'true');
    check('Apply does not steal focus', await settingsForm.getByRole('button', { name: 'Apply', exact: true }).evaluate(el => el === document.activeElement));
    const other = await browser.newContext();
    await other.addCookies([{ name: 'ticketopia_session', value: process.env.SAVED_OTHER_TOKEN, url: base }]);
    const otherMe = await (await other.request.get(base + '/api/v1/me')).json();
    check('Other account publishes while composer is mounted', (await other.request.put(base + '/api/v1/me/event-recommendations/ticketmaster:Browser_0', { data: { reason: '' }, headers: { 'X-CSRF-Token': otherMe.csrf_token } })).ok());
    await signed.waitForFunction(() => document.querySelector('[data-live-total="ticketmaster:Browser_0"] strong')?.textContent === '1', null, { timeout: 20000 });
    check('Filtered activity keeps authoritative unfiltered counts', true);
    check('Count update preserves composer and participation', await composer.evaluate(el => el === window.fixtureComposer && el.value === 'Keep this unsubmitted filter journey draft') && await signed.locator('[data-interest-form]:not([data-interest-edit]) button').getAttribute('aria-pressed') === 'true');
    await other.close();
    const fallback = await browser.newContext();
    await fallback.addInitScript(() => { window.EventSource = undefined; localStorage.setItem('ticketopia-live-filters-v1', JSON.stringify({ location: { mode: 'city', city: 'Berlin', country: 'DE' }, category_ids: ['Music'], artist_ids: [], venue_ids: [] })); });
    const fallbackPage = await fallback.newPage(); await fallbackPage.goto(base + '/happening-now');
    await fallbackPage.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    check('Filtered JSON fallback restores guest scope', await fallbackPage.locator('[data-live-list]').textContent().then(text => text.includes('Berlin music beyond twenty')));
    check('No browser errors', errors.length === 0);
    fs.writeFileSync(path.join(output, 'checks.json'), JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ checks: checks.length, output }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
