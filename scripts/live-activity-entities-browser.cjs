// Production routes with isolated MariaDB and seeded public catalog cache.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.SAVED_BASE_URL;
const output = path.resolve(__dirname, '../.impeccable/review/live-entities');
fs.mkdirSync(output, { recursive: true });
const checks = [], errors = [];
const check = (label, value) => { assert.ok(value, label); checks.push(label); };
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_EXECUTABLE });
  try {
    const owner = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await owner.addCookies([{ name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base }]);
    const page = await owner.newPage(); page.on('pageerror', e => errors.push(e.message));
    await page.goto(base + '/happening-now');
    const form = page.locator('[data-live-filter-form]');
    const count = async n => page.waitForFunction(n => document.querySelectorAll('[data-live-list] li').length === n, n);
    const prefs = async () => (await owner.request.get(base + '/api/v1/me/live-activity-preferences')).json();
    const picker = kind => form.locator(`[data-live-picker="${kind}"]`);
    const search = async kind => {
      await picker(kind).locator('[data-live-keyword]').fill('fixture');
      await picker(kind).locator('[data-live-search]').click();
      await picker(kind).locator('[data-live-results] label').first().waitFor();
    };
    const apply = async n => { await form.getByRole('button', { name: 'Apply', exact: true }).click(); await count(n); };
    await count(20); await form.locator('summary').click();
    await form.getByLabel('Location', { exact: true }).selectOption('city');
    await form.getByLabel('City', { exact: true }).fill('Berlin');
    await form.getByLabel('Two-letter country').fill('DE');
    await form.getByLabel('Music', { exact: true }).check();
    await search('artist'); await picker('artist').getByLabel('artist A', { exact: true }).check();
    check('Search and selection do not save', (await prefs()).revision === 1);
    await apply(2);
    check('Artist plus city and type finds complete-window matches', (await page.locator('[data-live-list]').textContent()).includes('Entity match 0'));
    await search('venue'); await picker('venue').getByLabel('venue Hall', { exact: true }).check(); await apply(1);
    check('Artist AND secondary venue', (await page.locator('[data-live-list]').textContent()).includes('Entity match 0'));
    check('Multi-entity facets do not inflate contributions', !(await page.locator('[data-live-list]').textContent()).includes('people recommended'));
    await page.route('**/api/v1/artists?*', route => route.fulfill({ status: 503, body: '{}' }));
    await picker('artist').locator('[data-live-search]').click();
    await picker('artist').getByText('Search could not load.', { exact: false }).waitFor();
    check('Lookup failure preserves selected artist and view', await picker('artist').getByLabel('artist A', { exact: true }).isChecked() && await page.locator('[data-live-list] li').count() === 1);
    await page.unroute('**/api/v1/artists?*'); await search('artist');
    await picker('artist').getByLabel('artist B', { exact: true }).check(); await apply(2);
    check('OR within artists, AND across venue', true);
    await picker('venue').getByRole('button', { name: 'Clear Venues' }).click(); await apply(3);
    check('Independent clear venue', (await prefs()).filters.venue_ids.length === 0);
    check('Apply is quiet', await page.locator('[data-live-badge]').textContent() === '' && await page.locator('[data-live-toasts] li').count() === 0);
    check('Named confirmed summary', (await page.locator('[data-live-summary]').textContent()).includes('artist A or artist B'));
    const pref = await prefs();
    const second = await owner.newPage(); await second.goto(base + '/happening-now');
    await second.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 3);
    check('Account selections and labels survive another tab', (await second.locator('[data-live-summary]').textContent()).includes('artist A or artist B'));
    await second.close();
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: 1000 });
      check('Picker no horizontal overflow ' + width, await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      if (width !== 390) await form.screenshot({ path: path.join(output, width + '.png') });
    }
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
    check('Enlarged picker wraps', await form.evaluate(el => [...el.querySelectorAll('*')].every(n => !n.getBoundingClientRect().width || n.getBoundingClientRect().right <= innerWidth + 1)));
    await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' });
    await page.keyboard.press('Tab');
    await picker('artist').locator('[data-live-search]').focus();
    check('Keyboard focus visible', await picker('artist').locator('[data-live-search]').evaluate(el => getComputedStyle(el).outlineStyle !== 'none'));
    if (process.env.AXE_SCRIPT) { await page.addScriptTag({ path: process.env.AXE_SCRIPT }); check('Whole-page accessibility', (await page.evaluate(async () => (await axe.run()).violations)).length === 0); }
    // Native forms use the same catalog and retain the original conditional revision.
    const native = await browser.newContext({ javaScriptEnabled: false });
    await native.addCookies([{ name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base }]);
    const np = await native.newPage(); await np.goto(base + '/happening-now');
    let nf = np.locator('[data-live-filter-form]'); await nf.locator('summary').click();
    await nf.getByLabel('Search Venues', { exact: true }).fill('fixture');
    await nf.getByRole('button', { name: 'Search Venues', exact: true }).click();
    await nf.getByLabel('venue Club', { exact: true }).waitFor();
    check('Native lookup retains draft and does not commit', await nf.getByLabel('artist A', { exact: true }).isChecked() && (await prefs()).revision === pref.revision);
    await nf.getByLabel('venue Club', { exact: true }).check(); await nf.getByRole('button', { name: 'Apply', exact: true }).click();
    check('Native artist/venue Apply', await np.locator('[data-live-list] li').count() === 1 && (await np.locator('[data-live-list]').textContent()).includes('Entity match 2'));
    await np.goto(base + '/me/preferences');
    nf = np.locator('form[action="/me/live-activity-preferences"]'); await nf.locator('summary').click();
    check('Equivalent account editor persists selected names', await nf.getByLabel('venue Club', { exact: true }).isChecked());
    await nf.getByRole('button', { name: 'Reset filters' }).click();
    check('Native Reset preserves enabled state', (await prefs()).filters.artist_ids.length === 0 && (await prefs()).enabled);
    await page.goto(base + '/happening-now'); await count(20); await form.locator('summary').click();
    await search('artist'); await picker('artist').getByLabel('artist A', { exact: true }).check();
    const resetRevision = (await prefs()).revision;
    await form.getByRole('button', { name: 'Reset filters', exact: true }).click();
    await page.waitForFunction(() => document.querySelectorAll('[data-live-picker] input[type=checkbox]:checked').length === 0);
    check('No-op Reset clears unsaved entity edits without revision bump', (await prefs()).revision === resetRevision);
    const guest = await browser.newContext();
    await guest.addInitScript(filters => localStorage.setItem('ticketopia-live-filters-v1', JSON.stringify(filters)), { location: { mode: 'all' }, category_ids: [], artist_ids: ['ticketmaster:A'], venue_ids: ['ticketmaster:Hall'] });
    const gp = await guest.newPage(); await gp.goto(base + '/happening-now');
    await gp.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    check('Guest restored public entity filters', (await gp.locator('[data-live-list]').textContent()).includes('Entity match 0'));
    check('Guest catalog lookup remains unauthorized', (await guest.request.get(base + '/api/v1/artists?keyword=fixture')).status() === 401 && (await guest.request.get(base + '/api/v1/artists/ticketmaster:A')).status() === 401);
    await gp.locator('[data-live-filter-form] summary').click();
    check('Guest picker explains sign-in', await gp.getByText('Sign in to search artists and venues.', { exact: true }).count() === 2);
    const storage = await gp.evaluate(() => localStorage.getItem('ticketopia-live-filters-v1'));
    check('Browser stores IDs only', !/artist A|venue Hall|actor|event_title|account_id/.test(storage));
    const publicResponse = await guest.request.get(base + '/api/v1/community/activity?filter=' + encodeURIComponent(JSON.stringify({ artist_ids: ['ticketmaster:A'], venue_ids: ['ticketmaster:Hall'] })));
    const dto = await publicResponse.text(); check('Public DTO has no matching facts', publicResponse.ok() && !/artist_ids|venue_ids|account_id/.test(dto));
    const guestNative = await browser.newContext({ javaScriptEnabled: false }); const gnp = await guestNative.newPage();
    await gnp.goto(base + '/happening-now?live_artist_ids=ticketmaster:A&live_venue_ids=ticketmaster:Hall');
    check('Native guest exact public filters', await gnp.locator('[data-live-list] li').count() === 1);
    const fallback = await browser.newContext();
    await fallback.addInitScript(() => { window.EventSource = undefined; localStorage.setItem('ticketopia-live-filters-v1', JSON.stringify({ location: { mode: 'all' }, category_ids: [], artist_ids: ['ticketmaster:A'], venue_ids: ['ticketmaster:Hall'] })); });
    const fp = await fallback.newPage(); await fp.goto(base + '/happening-now');
    await fp.waitForFunction(() => document.querySelectorAll('[data-live-list] li').length === 1);
    check('Entity-scoped snapshot fallback', (await fp.locator('[data-live-list]').textContent()).includes('Entity match 0'));
    check('No browser errors', errors.length === 0);
    fs.writeFileSync(path.join(output, 'checks.json'), JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ checks: checks.length, output }));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
