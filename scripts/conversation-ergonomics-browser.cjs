// Isolated local MariaDB accounts. Viewport reduction is not a real phone keyboard.
const {chromium, webkit} = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const engine = process.env.CONVERSATION_BROWSER_ENGINE || 'chromium';
const base = process.env.SAVED_BASE_URL;
const out = path.resolve(process.env.CONVERSATION_REVIEW_DIR || path.join(__dirname, '../.impeccable/review/conversation-ergonomics'), engine);
const report = {checks: [], accessibility: [], screenshots: [], errors: []};
const check = (name, result) => { assert.ok(result, name); report.checks.push(name); };
const pause = page => page.waitForFunction(() => !document.querySelector('[data-discussion-form][aria-busy="true"], [data-conversation-content][aria-busy="true"], [data-event-section-region][aria-busy="true"]'));
fs.mkdirSync(out, {recursive: true});
(async () => {
  const browser = await (engine === 'webkit' ? webkit : chromium).launch({headless: true, ...(engine === 'chromium' && process.env.CHROMIUM_EXECUTABLE ? {executablePath: process.env.CHROMIUM_EXECUTABLE} : {})});
  try {
    const owner = await browser.newContext({viewport: {width: 390, height: 844}, hasTouch: true});
    const other = await browser.newContext();
    for (const [context, token] of [[owner, process.env.SAVED_FIXTURE_TOKEN], [other, process.env.SAVED_OTHER_TOKEN]]) {
      await context.addCookies([{name: 'ticketopia_session', value: token, url: base}]);
    }
    const otherMe = await (await other.request.get(base + '/api/v1/me')).json();
    const id = 'ticketmaster:Browser_0';
    const endpoint = '/api/v1/events/' + id + '/discussions';
    const page = await owner.newPage();
    page.on('pageerror', error => report.errors.push(error.message));
    const capture = async name => {
      await page.evaluate(async () => { await document.fonts.ready; });
      check(name + ' no horizontal overflow', await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
      const file = path.join(out, name + '.png');
      await page.screenshot({path: file, fullPage: true}); report.screenshots.push(file);
      if (process.env.AXE_SCRIPT) {
        await page.addScriptTag({path: process.env.AXE_SCRIPT});
        const violations = await page.evaluate(async () => (await axe.run(document, {runOnly: {type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa', 'wcag22aa']}})).violations);
        report.accessibility.push({name, violations});
        check(name + ' axe ' + JSON.stringify(violations.map(v => ({id: v.id, nodes: v.nodes.map(n => n.failureSummary)}))), !violations.length);
      }
    };
    await page.goto(base + '/events/' + id + '/discussions?return_to=' + encodeURIComponent('/community/discussions?city=Berlin&limit=1'));
    await page.locator('.discussion-editor > summary').click();
    await page.locator('.discussion-composer textarea').fill('Question from the phone journey');
    await page.getByRole('button', {name: 'Post question or tip', exact: true}).click();
    await page.waitForURL(url => /\/discussions\/[^/]+$/.test(url.pathname));
    const roots = await (await owner.request.get(base + endpoint)).json();
    const root = roots.items.find(post => post.body === 'Question from the phone journey');
    assert.ok(root);
    const thread = '/events/' + id + '/discussions/' + root.id;
    check('Question confirms the exact root and collection origin', new URL(page.url()).hash === '#post-' + root.id && new URL(page.url()).searchParams.get('return_to') === '/community/discussions?city=Berlin&limit=1');
    const replyResult = await other.request.post(base + endpoint + '/' + root.id + '/replies', {data: {body: 'An answer with a practical tip'}, headers: {'X-CSRF-Token': otherMe.csrf_token, 'Idempotency-Key': 'phone-other-reply-0001'}});
    assert.equal(replyResult.status(), 201);
    const reply = await replyResult.json();
    await page.goto(base + thread);
    let documents = 0;
    page.on('request', request => { if (request.isNavigationRequest() && request.frame() === page.mainFrame()) documents++; });
    const composer = () => page.locator('#discussion-composer .discussion-composer');
    const field = () => composer().locator('textarea');
    await field().fill('A draft for the whole conversation');
    const rootKey = await composer().locator('[name=idempotency_key]').inputValue();
    await page.locator('#post-' + reply.id).getByRole('link', {name: 'Reply', exact: true}).click();
    await page.waitForURL(url => url.searchParams.get('reply_to') === reply.id);
    await pause(page);
    check('Reply target changes without carrying the wrong draft', await field().inputValue() === '' && await composer().locator('[name=parent_id]').inputValue() === reply.id);
    await field().fill('Reply-target draft ' + 'long text\n'.repeat(250));
    const targetDraft = await field().inputValue();
    const targetKey = await composer().locator('[name=idempotency_key]').inputValue();
    await page.setViewportSize({width: 390, height: 420});
    await field().focus();
    await page.waitForFunction(() => {
      const field = document.querySelector('#discussion-composer textarea').getBoundingClientRect();
      const action = document.querySelector('#discussion-composer button[type=submit]').getBoundingClientRect();
      const nav = document.querySelector('.bottom-nav').getBoundingClientRect();
      return field.top >= 0 && action.bottom <= Math.min(innerHeight, nav.top);
    });
    check('Long draft and publish action fit in a reduced-height viewport', await field().inputValue() === targetDraft);
    check('Only one active writing field is visible', await page.locator('.discussion-composer textarea:visible').count() === 1);
    await capture('phone-short-long-draft');
    await page.setViewportSize({width: 1440, height: 900});
    check('Resize preserves target draft and retry identity', await field().inputValue() === targetDraft && await composer().locator('[name=idempotency_key]').inputValue() === targetKey);
    await capture('desktop-draft');
    await page.goBack();
    await page.waitForURL(url => !url.searchParams.has('reply_to'));
    await pause(page);
    check('Back restores the conversation draft and original key', await field().inputValue() === 'A draft for the whole conversation' && await composer().locator('[name=idempotency_key]').inputValue() === rootKey);
    await page.goForward();
    await page.waitForURL(url => url.searchParams.get('reply_to') === reply.id);
    await pause(page);
    check('Forward restores the separate reply-target draft', await field().inputValue() === targetDraft);
    await page.reload();
    check('Reload preserves target and draft', await field().inputValue() === targetDraft && await composer().locator('[name=parent_id]').inputValue() === reply.id);
    await composer().getByText('Discard draft', {exact: true}).click();
    check('Discard requires a deliberate second action', await field().inputValue() === targetDraft);
    await composer().getByRole('button', {name: 'Discard this draft', exact: true}).click();
    check('Discard clears only this target and starts a fresh identity', await field().inputValue() === '' && await composer().locator('[name=idempotency_key]').inputValue() !== targetKey);
    await page.reload();
    check('Discarded draft does not reappear after reload', await field().inputValue() === '');
    await field().fill('A reply interrupted after the database committed');
    const immutableBody = await field().inputValue();
    const immutableKey = await composer().locator('[name=idempotency_key]').inputValue();
    const immutableScope = await composer().getAttribute('data-discussion-draft');
    let sent;
    let release;
    const held = new Promise(resolve => { release = resolve; });
    let reached;
    const committed = new Promise(resolve => { reached = resolve; });
    await page.route('**/discussion-actions', async route => {
      sent = new URLSearchParams(route.request().postData());
      const response = await route.fetch();
      assert.equal(response.status(), 200);
      reached();
      await held;
      await route.abort('failed');
    });
    await field().focus();
    await composer().getByRole('button', {name: 'Publish reply', exact: true}).click();
    await committed;
    check('Pending state is explicit and retains a selectable field', await composer().getAttribute('aria-busy') === 'true' && await field().evaluate(el => el.readOnly && !el.disabled) && await composer().getByRole('button', {name: 'Publish reply'}).isDisabled());
    // A repeated submit cannot leave a second write while the first is pending.
    await composer().evaluate(form => form.requestSubmit(form.querySelector('button[type=submit]')));
    release();
    await composer().locator('[data-discussion-error]').waitFor({state: 'visible'});
    check('Interrupted acknowledgment is honest and keeps an immutable retry', (await composer().locator('[data-discussion-error]').innerText()).includes('may already be published') && await field().evaluate(el => el.readOnly) && await composer().locator('[name=idempotency_key]').inputValue() === immutableKey);
    check('Reply payload includes the intended target', sent.get('parent_id') === reply.id && sent.get('body') === immutableBody);
    await page.unroute('**/discussion-actions');
    await page.reload();
    check('Uncertain retry survives reload with payload/key/target locked', await field().inputValue() === immutableBody && await field().evaluate(el => el.readOnly) && await composer().locator('[name=idempotency_key]').inputValue() === immutableKey);
    documents = 0;
    await page.route('**/discussion-actions', route => route.fulfill({status: 401, contentType: 'application/problem+json', body: JSON.stringify({detail: 'Sign in again to continue.'})}));
    await composer().getByRole('button', {name: 'Retry unchanged contribution'}).click();
    await composer().getByRole('link', {name: 'Sign in to continue'}).waitFor();
    check('Session failure after uncertainty cannot unlock a new payload', await field().evaluate(el => el.readOnly) && await field().inputValue() === immutableBody);
    await page.unroute('**/discussion-actions');
    await composer().getByRole('button', {name: 'Retry unchanged contribution'}).click();
    await page.waitForURL(url => url.hash.startsWith('#post-'));
    await page.locator('.discussion-post > .discussion-body').filter({hasText: immutableBody}).waitFor();
    await pause(page);
    const replies = await (await owner.request.get(base + endpoint + '/' + root.id + '/replies')).json();
    const published = replies.items.filter(post => post.body === immutableBody);
    check('Retry confirms exactly one contribution after interrupted acknowledgment', published.length === 1 && published[0].parent_id === reply.id);
    const selection = await page.evaluate(() => ({hash: location.hash, active: document.activeElement.id}));
    check('Publication selects and focuses the confirmed reply ' + JSON.stringify(selection), selection.hash === '#post-' + published[0].id && selection.active === 'post-' + published[0].id);
    check('Confirmed target draft is cleared without losing another target draft', await page.evaluate(scope => sessionStorage.getItem('ticketopia:discussion:' + scope) === null, immutableScope) && await field().inputValue() === 'A draft for the whole conversation');
    await field().fill('An unrelated reply draft kept while acknowledging help');
    const helpful = () => page.locator('#post-' + reply.id).getByRole('button', {name: 'Helpful'});
    await helpful().scrollIntoViewIfNeeded();
    await helpful().focus();
    const before = await page.evaluate(() => ({scroll: scrollY, history: history.length}));
    await helpful().click();
    await page.locator('#post-' + reply.id + ' button[aria-pressed=true]').waitFor();
    await pause(page);
    check('Helpful confirms in place without history or reading-position loss', await page.evaluate(previous => Math.abs(scrollY - previous.scroll) < 2 && history.length === previous.history, before));
    check('Helpful restores focus and preserves the unrelated draft', await helpful().evaluate(button => button === document.activeElement) && await field().inputValue() === 'An unrelated reply draft kept while acknowledging help');
    await page.locator('#post-' + root.id).getByText('Edit your contribution', {exact: true}).click();
    await page.locator('#post-' + root.id + ' textarea').fill('An unsaved question edit');
    await field().waitFor({state: 'hidden'});
    check('Owner edit hides the reply composer instead of competing with it', await page.locator('.discussion-composer textarea:visible').count() === 1 && !await field().isVisible());
    await page.locator('#post-' + published[0].id).getByText('Edit your contribution', {exact: true}).click();
    await page.waitForFunction(() => document.querySelectorAll('.discussion-editor[open]').length === 1);
    check('Switching editors keeps one active composer and the previous edit draft', await page.locator('.discussion-editor[open]').count() === 1 && await page.locator('#post-' + root.id + ' textarea').inputValue() === 'An unsaved question edit');
    await page.locator('#post-' + published[0].id + ' .discussion-editor > summary').click();
    await field().waitFor({state: 'visible'});
    check('Closing an editor restores the reply composer', await field().isVisible());
    check('Thread transitions and writes use no document navigation', documents === 0);
    await page.setViewportSize({width: 320, height: 640});
    await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; });
    await capture('phone-enlarged-conversation');
    await page.evaluate(() => { document.documentElement.style.fontSize = ''; });
    // A confirmed write followed by a failed read must offer GET recovery, not
    // invite reposting the already-saved contribution.
    await page.route('**/events/*/discussions/*', route => route.request().method() === 'GET' ? route.abort('failed') : route.continue());
    await helpful().click();
    await page.getByRole('button', {name: 'Retry conversation', exact: true}).waitFor();
    check('Confirmed action and failed refresh are distinguished', (await page.locator('[data-conversation-status]').innerText()).includes('Helpful choice saved.') && await field().inputValue() === 'An unrelated reply draft kept while acknowledging help');
    await page.unroute('**/events/*/discussions/*');
    await page.getByRole('button', {name: 'Retry conversation', exact: true}).click();
    await page.locator('#post-' + reply.id + ' button[aria-pressed=false]').waitFor();
    await pause(page);
    await capture('phone-confirmed-conversation');
    // Put the next contribution beyond the default twenty-reply page without
    // exceeding the other account's twenty-attempt creation limit.
    for (let i = 0; i < 19; i++) {
      const result = await other.request.post(base + endpoint + '/' + root.id + '/replies', {data: {body: 'Retained paging reply ' + i}, headers: {'X-CSRF-Token': otherMe.csrf_token, 'Idempotency-Key': 'phone-paging-reply-' + String(i).padStart(4, '0')}});
      assert.equal(result.status(), 201);
    }
    const native = await browser.newContext({javaScriptEnabled: false, viewport: {width: 320, height: 640}});
    await native.addCookies([{name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base}]);
    const nativePage = await native.newPage();
    await nativePage.goto(base + thread + '?reply_to=' + reply.id);
    const nativeForm = nativePage.locator('#discussion-composer .discussion-composer');
    const nativeKey = await nativeForm.locator('[name=idempotency_key]').inputValue();
    await nativeForm.locator('textarea').fill('   ');
    await nativeForm.getByRole('button', {name: 'Publish reply'}).click();
    check('Native validation retains body/key/target and safe conversation return', await nativePage.locator('.discussion-composer textarea').inputValue() === '   ' && await nativePage.locator('[name=idempotency_key]').inputValue() === nativeKey && await nativePage.locator('[name=parent_id]').inputValue() === reply.id && (await nativePage.getByRole('link', {name: 'Back to conversation'}).getAttribute('href')).includes('reply_to=' + reply.id));
    await nativePage.locator('.discussion-composer textarea').fill('A native reply with the same retained target');
    await nativePage.getByRole('button', {name: 'Retry contribution'}).click();
    await nativePage.waitForURL(url => url.hash.startsWith('#post-'));
    check('Native explicit retry publishes and selects the exact contribution', new URL(nativePage.url()).hash.startsWith('#post-') && await nativePage.locator('.discussion-post > .discussion-body').filter({hasText: 'A native reply with the same retained target'}).count() === 1);
    check('Confirmed off-page reply is visible once alongside the paginated conversation', await nativePage.getByRole('heading', {name: 'Selected contribution', exact: true}).count() === 1 && await nativePage.locator('.discussion-replies .discussion-post').count() === 20);
    // Blocked browser storage still supports same-document transitions.
    const blocked = await browser.newContext({viewport: {width: 390, height: 844}});
    await blocked.addCookies([{name: 'ticketopia_session', value: process.env.SAVED_FIXTURE_TOKEN, url: base}]);
    await blocked.addInitScript(() => { Storage.prototype.setItem = Storage.prototype.getItem = Storage.prototype.removeItem = () => { throw new Error('Blocked storage'); }; });
    const blockedPage = await blocked.newPage();
    blockedPage.on('pageerror', error => report.errors.push(error.message));
    await blockedPage.goto(base + thread);
    await blockedPage.locator('#discussion-composer textarea').fill('In-memory reply draft');
    await blockedPage.locator('#post-' + reply.id).getByRole('link', {name: 'Reply', exact: true}).click();
    await blockedPage.waitForURL(url => url.searchParams.has('reply_to'));
    await pause(blockedPage);
    await blockedPage.goBack();
    await blockedPage.waitForURL(url => !url.searchParams.has('reply_to'));
    await pause(blockedPage);
    check('Blocked storage retains scoped in-page drafts through target/Back', await blockedPage.locator('#discussion-composer textarea').inputValue() === 'In-memory reply draft');
    await page.goto(base + '/community/discussions?city=Berlin&limit=1');
    await page.locator('.discussion-list [data-thread-link]').click();
    await page.waitForURL(url => url.pathname === thread);
    await page.locator('#post-' + root.id).getByRole('link', {name: 'Reply', exact: true}).click();
    await page.waitForURL(url => url.searchParams.get('reply_to') === root.id);
    await pause(page);
    await page.locator('#post-' + reply.id).getByRole('link', {name: 'Reply', exact: true}).click();
    await page.waitForURL(url => url.searchParams.get('reply_to') === reply.id);
    await pause(page);
    await page.locator('[data-return-results]').click();
    await page.waitForURL(url => url.pathname === '/community/discussions');
    check('Collection return crosses all in-place thread transitions', new URL(page.url()).searchParams.get('city') === 'Berlin' && new URL(page.url()).searchParams.get('limit') === '1');
    check('No browser runtime errors', !report.errors.length);
    fs.writeFileSync(path.join(out, 'checks.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify({engine, checks: report.checks.length, accessibility: report.accessibility.length, screenshots: report.screenshots.length}));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
